-- The starting roles change, as the Decisions Log sets out: the Planner becomes the Product Manager,
-- the Feature Lead is added, and every starting role is given the name, description, and grants the
-- shared starting roles set out, whether or not someone has changed it, since databases are reset
-- rather than converted. No role made by hand can already be named Product Manager or Feature
-- Lead: on a new database, the migrations run before anyone can make a role.

UPDATE "fathom"."roles" SET "key" = 'product-manager' WHERE "key" = 'planner';
