INSERT INTO "fathom"."roles" ("key", "name", "description") VALUES
  ('team-member', 'Team Member', 'Sees the plan, including everyone''s work assignments, and the org chart.'),
  ('product-manager', 'Product Manager', 'Edits projects, proposals, features, milestones, releases, products, customers, and estimates across the whole plan, and approves or rejects drafts of the plan.'),
  ('feature-lead', 'Feature Lead', 'Sees the plan and people''s General details, edits features, estimates, and allocations, and proposes feature teams.'),
  ('project-manager', 'Project Manager', 'Edits the plan, sees people and the hiring plan, and approves or rejects drafts of the data the role sees, including feature teams.'),
  ('engineering-manager', 'Engineering Manager', 'Edits the plan and allocations, sees people, with everyone''s Restricted details and the hiring plan, colours teams on the org chart, and proposes feature teams.'),
  ('engineering-director', 'Engineering Director', 'Edits and approves the plan, features, allocations, people, feature teams, the hiring plan, and configuration, sees all Restricted and Confidential data, and sees accounts, roles, settings, and the access history without changing them.'),
  ('workforce-administrator', 'Workforce Administrator', 'Sees the plan, maintains people, teams, reporting lines, feature teams, the hiring plan, and planning configuration, and sees all Restricted and Confidential data.'),
  ('executive', 'Executive', 'Sees the plan, people, with their Restricted and Confidential data and the hiring plan, configuration, accounts, roles, settings, and both histories, without changing them.'),
  ('resource-planner', 'Resource Planner', 'Sees the plan and people''s General details, and edits allocations across the whole plan.'),
  ('administrator', 'Administrator', 'Manages user accounts, roles, and system settings, without access to the plan or people''s data.')
